from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from evalscope_ext.data_loader import load_benchmark_bundle
from evalscope_ext.pruning.multi_objective import PruneConfig, build_joined_from_records, select_indices


@dataclass
class PrunedBenchmarkSpec:
    name: str
    source_benchmark: str
    default_prune_ratio: float = 0.1
    default_strategy: str = "multi_objective"


PRUNED_BENCHMARKS = {
    "live_code_bench_pruned": PrunedBenchmarkSpec("live_code_bench_pruned", "live_code_bench_v5"),
    "aa_lcr_pruned": PrunedBenchmarkSpec("aa_lcr_pruned", "aa_lcr"),
    "mmmu_encoder_probe_pruned": PrunedBenchmarkSpec("mmmu_encoder_probe_pruned", "mmmu", 0.05),
}


def resolve_pruned_indices(
    eval_root: Path,
    benchmark_name: str,
    dataset_args: dict[str, Any] | None = None,
) -> list[int]:
    dataset_args = dataset_args or {}
    spec = PRUNED_BENCHMARKS[benchmark_name]
    config = PruneConfig(
        prune_ratio=float(dataset_args.get("prune_ratio", spec.default_prune_ratio)),
        seed=int(dataset_args.get("seed", 42)),
        strategy=str(dataset_args.get("pruning_strategy", spec.default_strategy)),
    )
    bundle = load_benchmark_bundle(eval_root, spec.source_benchmark)
    joined = build_joined_from_records(bundle)
    all_records = [r for rs in bundle.values() for r in rs]
    return select_indices(all_records, joined, config)


def try_register_with_evalscope() -> None:
    """Register pruned benchmark aliases when evalscope is installed."""
    try:
        from evalscope.api.registry import register_benchmark
        from evalscope.api.benchmark import BenchmarkMeta
    except Exception:
        return

    for name, spec in PRUNED_BENCHMARKS.items():
        register_benchmark(
            BenchmarkMeta(
                name=name,
                pretty_name=name.replace("_", " ").title(),
                dataset_id=str(spec.source_benchmark),
                tags=["pruned", "custom"],
                description=f"Pruned subset of {spec.source_benchmark} generated by evalscope_ext.",
                subset_list=["default"],
            )
        )
